# ==========================================
# ÉTAPE 5: Créer la solution .NET
# ==========================================

Write-Host "🔨 Création de la solution .NET..." -ForegroundColor Yellow

if (-not (Test-Path "GMS.sln")) {
    dotnet new sln -n GMS
    Write-Host "  ✅ Solution GMS.sln créée" -ForegroundColor Green
} else {
    Write-Host "  ⏭️  GMS.sln existe déjà" -ForegroundColor Gray
}

Write-Host ""

# ==========================================
# ÉTAPE 6: Créer les projets
# ==========================================

Write-Host "📦 Création des projets .NET..." -ForegroundColor Yellow

$projects = @(
    @{Name="GMS.Domain"; Type="classlib"; Path="src/GMS.Domain"},
    @{Name="GMS.Application"; Type="classlib"; Path="src/GMS.Application"},
    @{Name="GMS.Infrastructure"; Type="classlib"; Path="src/GMS.Infrastructure"},
    @{Name="GMS.Shared"; Type="classlib"; Path="src/GMS.Shared"},
    @{Name="GMS.Desktop"; Type="wpf"; Path="src/GMS.Desktop"},
    @{Name="GMS.Tests"; Type="xunit"; Path="src/GMS.Tests"}
)

foreach ($project in $projects) {
    $projectFile = "$($project.Path)/$($project.Name).csproj"
    
    if (-not (Test-Path $projectFile)) {
        dotnet new $($project.Type) -n $($project.Name) -o $($project.Path)
        dotnet sln add $projectFile
        Write-Host "  ✅ $($project.Name) créé" -ForegroundColor Green
    } else {
        Write-Host "  ⏭️  $($project.Name) existe déjà" -ForegroundColor Gray
    }
}

Write-Host ""

# ==========================================
# ÉTAPE 7: Configurer les références entre projets
# ==========================================

Write-Host "🔗 Configuration des références entre projets..." -ForegroundColor Yellow

dotnet add src/GMS.Application/GMS.Application.csproj reference src/GMS.Domain/GMS.Domain.csproj
dotnet add src/GMS.Infrastructure/GMS.Infrastructure.csproj reference src/GMS.Domain/GMS.Domain.csproj
dotnet add src/GMS.Infrastructure/GMS.Infrastructure.csproj reference src/GMS.Application/GMS.Application.csproj
dotnet add src/GMS.Desktop/GMS.Desktop.csproj reference src/GMS.Application/GMS.Application.csproj
dotnet add src/GMS.Desktop/GMS.Desktop.csproj reference src/GMS.Infrastructure/GMS.Infrastructure.csproj
