    ".github/workflows",
    ".github/ISSUE_TEMPLATE",
    "docs/screenshots",
    "scripts",
    "src/GMS.Domain",
    "src/GMS.Application",
    "src/GMS.Infrastructure",
    "src/GMS.Desktop",
    "src/GMS.Shared",
    "src/GMS.Tests",
    "logs",
    "backups"
)

foreach ($folder in $folders) {
    if (-not (Test-Path $folder)) {
        New-Item -ItemType Directory -Path $folder -Force | Out-Null
        Write-Host "  ✅ $folder" -ForegroundColor Green
    } else {
        Write-Host "  ⏭️  $folder (existe déjà)" -ForegroundColor Gray
    }
}

Write-Host ""

